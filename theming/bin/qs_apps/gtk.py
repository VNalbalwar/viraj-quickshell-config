"""GTK3 + GTK4/libadwaita (Nautilus, Thunar, Settings...): named colors, applied to running apps."""
import os
import subprocess

from .palette import is_dark, mix, readable_on, shade

HOME = os.path.expanduser("~")
GTK3 = os.path.join(HOME, ".config/gtk-3.0/gtk.css")
GTK4 = os.path.join(HOME, ".config/gtk-4.0/gtk.css")
BACKUP = os.path.join(HOME, ".config/gtk-4.0/gtk.css.symlink-backup")


def css(p):
    dark = is_dark(p)
    bg, fg = p["background"], p["foreground"]
    s = lambda a, base=bg: shade(p, base, a)
    accent = p["color4"]
    c = {
        "accent_bg_color": accent, "accent_fg_color": readable_on(accent), "accent_color": p["color12"],
        "destructive_bg_color": p["color1"], "destructive_fg_color": readable_on(p["color1"]), "destructive_color": p["color9"],
        "success_bg_color": p["color2"], "success_fg_color": readable_on(p["color2"]), "success_color": p["color10"],
        "warning_bg_color": p["color3"], "warning_fg_color": readable_on(p["color3"]), "warning_color": p["color11"],
        "error_bg_color": p["color1"], "error_fg_color": readable_on(p["color1"]), "error_color": p["color9"],
        "window_bg_color": bg, "window_fg_color": fg,
        "view_bg_color": s(0.025), "view_fg_color": fg,
        "headerbar_bg_color": s(0.05), "headerbar_fg_color": fg, "headerbar_border_color": s(0.12),
        "headerbar_backdrop_color": bg,
        "sidebar_bg_color": s(0.04), "sidebar_fg_color": fg, "sidebar_backdrop_color": bg,
        "secondary_sidebar_bg_color": s(0.03), "secondary_sidebar_fg_color": fg,
        "card_bg_color": s(0.07), "card_fg_color": fg,
        "dialog_bg_color": s(0.06), "dialog_fg_color": fg,
        "popover_bg_color": s(0.08), "popover_fg_color": fg,
        "thumbnail_bg_color": s(0.08), "thumbnail_fg_color": fg,
        # GTK3 / adw-gtk3 + older names
        "bg_color": bg, "fg_color": fg, "base_color": s(0.025), "text_color": fg,
        "selected_bg_color": accent, "selected_fg_color": readable_on(accent),
    }
    lines = ["/* Generated by qs-theme (theming/bin/qs_apps/gtk.py) - follows the wallpaper / theme. */", ""]
    lines += [f"@define-color {k} {v};" for k, v in c.items()]
    return "\n".join(lines) + "\n"


def write(path, text, head=""):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.islink(path):
        if "gtk-4.0" in path and not os.path.lexists(BACKUP):
            os.rename(path, BACKUP)                     # keep the original adw-gtk3 link, don't delete it
        else:
            os.unlink(path)
    with open(path + ".tmp", "w") as f:
        f.write(head + text)
    os.replace(path + ".tmp", path)


def gset(key, value):
    subprocess.run(["gsettings", "set", "org.gnome.desktop.interface", key, value], capture_output=True)


def apply(p):
    dark = is_dark(p)
    text = css(p)
    variant = "adw-gtk3-dark" if dark else "adw-gtk3"
    write(GTK3, text)
    write(GTK4, text, head=f'@import url("file:///usr/share/themes/{variant}/gtk-4.0/gtk.css");\n')
    # light/dark for libadwaita + the GTK theme; changing these is also what makes running apps re-read their CSS
    gset("color-scheme", "prefer-dark" if dark else "prefer-light")
    gset("gtk-theme", variant)
