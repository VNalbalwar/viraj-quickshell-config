"""Neovim (NvChad / base46): generates the `wallust` theme and reloads every running nvim."""
import glob
import os
import subprocess

from .palette import is_dark, mix, shade, with_lightness

HOME = os.path.expanduser("~")
THEME = os.path.join(HOME, ".config/nvim/lua/themes/wallust.lua")


def theme_lua(p):
    bg, fg = p["background"], p["foreground"]
    dark = is_dark(p)
    s = lambda a, base=bg: shade(p, base, a)
    b30 = {
        "white": fg, "darker_black": mix(bg, "#000000" if dark else "#FFFFFF", 0.25), "black": bg,
        "black2": s(0.04), "one_bg": s(0.07), "one_bg2": s(0.12), "one_bg3": s(0.17),
        "grey": s(0.24), "grey_fg": s(0.30), "grey_fg2": s(0.36), "light_grey": s(0.44),
        "red": p["color1"], "baby_pink": p["color9"], "pink": p["color13"], "line": s(0.10),
        "green": p["color2"], "vibrant_green": p["color10"], "nord_blue": p["color12"], "blue": p["color4"],
        "yellow": p["color3"], "sun": p["color11"], "purple": p["color5"],
        "dark_purple": with_lightness(p["color5"], -0.08), "teal": p["color6"],
        "orange": mix(p["color1"], p["color3"], 0.5), "cyan": p["color14"],
        "statusline_bg": s(0.03), "lightbg": s(0.09), "pmenu_bg": p["color4"], "folder_bg": p["color4"],
        "lavender": p["color12"],
    }
    b16 = {
        "base00": bg, "base01": s(0.05), "base02": s(0.10), "base03": mix(bg, fg, 0.42), "base04": mix(bg, fg, 0.62),
        "base05": fg, "base06": mix(fg, "#FFFFFF" if dark else "#000000", 0.12), "base07": mix(fg, "#FFFFFF" if dark else "#000000", 0.25),
        "base08": p["color1"], "base09": mix(p["color1"], p["color3"], 0.5), "base0A": p["color3"], "base0B": p["color2"],
        "base0C": p["color6"], "base0D": p["color4"], "base0E": p["color5"], "base0F": with_lightness(p["color1"], -0.1),
    }
    body = lambda name, d: "M.%s = {\n%s\n}\n" % (name, "\n".join(f'  {k} = "{v}",' for k, v in d.items()))
    return ("-- Generated by qs-theme (theming/bin/qs_apps/nvim.py) - do not edit; it follows the wallpaper / theme.\n"
            "local M = {}\n\n" + body("base_30", b30) + "\n" + body("base_16", b16) +
            f'\nM.polish_hl = {{}}\n\nM.type = "{"dark" if dark else "light"}"\n\nreturn M\n')


RELOAD = ('luaeval("(function() package.loaded[\\"themes.wallust\\"] = nil; '
          'pcall(function() require(\\"nvchad.utils\\").reload() end) return 1 end)()")')


def apply(p):
    if not os.path.isdir(os.path.join(HOME, ".config/nvim")):
        return
    os.makedirs(os.path.dirname(THEME), exist_ok=True)
    with open(THEME + ".tmp", "w") as f:
        f.write(theme_lua(p))
    os.replace(THEME + ".tmp", THEME)
    run = os.environ.get("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")
    for sock in glob.glob(os.path.join(run, "nvim.*.0")):          # every running nvim, live
        try:
            subprocess.run(["nvim", "--server", sock, "--remote-expr", RELOAD],
                           capture_output=True, timeout=3)
        except (subprocess.TimeoutExpired, OSError):
            pass
